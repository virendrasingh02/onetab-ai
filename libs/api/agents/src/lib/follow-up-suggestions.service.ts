import { Injectable, Logger } from '@nestjs/common';
import { AICredentialService, AIInfrastructureService } from '@org/api-ai';
import type { AIProvider, StructuredMessageAction } from '@org/types';

export interface FollowUpContext {
  workspaceId: string;
  provider?: string | null;
  model?: string | null;
  agentName: string;
  agentRole?: string;
  /** What the person asked. */
  question: string;
  /** What the agent answered. */
  answer: string;
  /** Tools the agent used for this answer — hints at what it can do next. */
  toolNames?: string[];
}

const MAX_SUGGESTIONS = 4;
const MAX_LABEL_LENGTH = 90;

/** Pulls a JSON string array out of a model reply, tolerating prose/fences. */
export function parseFollowUps(raw: string): string[] {
  const match = /\[[\s\S]*\]/.exec(raw);
  if (!match) return [];
  try {
    const parsed: unknown = JSON.parse(match[0]);
    if (!Array.isArray(parsed)) return [];
    const seen = new Set<string>();
    const out: string[] = [];
    for (const item of parsed) {
      if (typeof item !== 'string') continue;
      const text = item.trim().replace(/^["'\s-]+|["'\s]+$/g, '');
      const key = text.toLowerCase();
      if (!text || text.length > MAX_LABEL_LENGTH || seen.has(key)) continue;
      seen.add(key);
      out.push(text);
      if (out.length === MAX_SUGGESTIONS) break;
    }
    return out;
  } catch {
    return [];
  }
}

/**
 * Suggests the next things to ask after an agent answers — generated by the
 * same AI gateway from the actual question and answer (never a canned list),
 * so every suggestion is something this agent can plausibly do next.
 */
@Injectable()
export class FollowUpSuggestionsService {
  private readonly logger = new Logger(FollowUpSuggestionsService.name);

  constructor(
    private readonly ai: AIInfrastructureService,
    private readonly credentials: AICredentialService,
  ) {}

  async suggest(ctx: FollowUpContext): Promise<StructuredMessageAction[]> {
    const answer = ctx.answer.trim();
    if (!answer || !ctx.question.trim()) return [];
    try {
      const provider = (ctx.provider || 'nvidia') as AIProvider;
      const cred = await this.credentials.resolveCredential(provider, {
        workspaceId: ctx.workspaceId,
      });
      const tools = ctx.toolNames?.length ? `\nTools it used: ${ctx.toolNames.join(', ')}` : '';
      const res = await this.ai.chat({
        provider,
        model: ctx.model || undefined,
        apiKey: cred.apiKey,
        baseUrl: cred.baseUrl,
        temperature: 0.5,
        maxTokens: 1500,
        messages: [
          {
            role: 'system',
            content: [
              `You suggest follow-up prompts a user could send next to "${ctx.agentName}"${ctx.agentRole ? ` (${ctx.agentRole})` : ''}.`,
              `Write ${MAX_SUGGESTIONS} short, specific prompts (max 12 words each) written from the user's point of view,`,
              'each a natural next step based on the question and answer below — deeper detail, a related action the agent can take, or a narrower view.',
              "Reply in the user's language. Never repeat the question. No numbering.",
              'Output ONLY a JSON array of strings.',
            ].join(' '),
          },
          {
            role: 'user',
            content: `User asked: ${ctx.question.slice(0, 800)}\n\nAgent answered: ${answer.slice(0, 2500)}${tools}`,
          },
        ],
      });
      return parseFollowUps(res.message.content ?? '').map((label, index) => ({
        id: `follow-up-${index}`,
        label,
        actionType: 'follow_up',
        payload: { prompt: label },
      }));
    } catch (error) {
      // Suggestions are a nicety — the answer is already delivered.
      this.logger.warn(
        `Follow-up suggestions skipped: ${error instanceof Error ? error.message : String(error)}`,
      );
      return [];
    }
  }
}
